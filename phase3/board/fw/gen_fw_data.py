"""Phase 3 board (v6 Zn-ion): export the C-part constants and the VAL cells (never test) for the on-board streaming app.
Writes fw/zn_params.h (label scaler, tag) and fw/zn_data.c (per val cell: cycle curves [k][3][300] float32 in external
flash via .rodata, true EOL, host reference EOL per prefix from the deployed chain E fp32 -> F INT8 -> C glue -> H fp32).
Usage: BL_SPLIT=2021 python phase3/board/fw/gen_fw_data.py"""
import sys
from pathlib import Path

import numpy as np
import onnxruntime as ort

FW = Path(__file__).resolve().parent; B = FW.parent; ROOT = B.parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(B))
import prepare  # noqa: E402
from st_int8 import RUNS, summaries  # noqa: E402

X = ROOT / "phase3" / "export"


def arr(name, a, ctype="float"):
    a = np.asarray(a).ravel()
    fl = lambda v: (lambda t: t if ("." in t or "e" in t or "n" in t) else t + ".0")(f"{float(v):.9g}") + "f"
    body = ",".join(fl(v) if ctype == "float" else str(int(v)) for v in a)
    return f"static const {ctype} {name}[{a.size}] = {{{body}}};\n"


if __name__ == "__main__":
    split = prepare.SPLIT; eid = RUNS[split]
    payload = prepare._load_locked_cache(); mu, s = float(payload["label_scaler"]["mean"]), float(payload["label_scaler"]["scale"])
    sE = ort.InferenceSession(str(X / f"{eid}_E.onnx")); sF = ort.InferenceSession(str(B / f"{eid}_F_int8.onnx"))
    sH = ort.InferenceSession(str(X / f"{eid}_H.onnx"))
    (FW / "zn_params.h").write_text(
        f"/* generated by gen_fw_data.py for {eid} (split {split}) */\n#pragma once\n#define ZN_TAG \"{eid} split{split}\"\n"
        f"#define ZN_D 64\n#define ZN_LABEL_MEAN {mu!r}\n#define ZN_LABEL_SCALE {s!r}\n"
        "typedef struct { int k; float eol; const float *curves; const float *ref_eol; } zn_cell_t;\n"
        "extern const zn_cell_t zn_cells[]; extern const int zn_ncells;\n")
    parts, cells, mape_ref, tgt_all = ["#include \"zn_params.h\"\n/* const data -> .rodata -> XSPI2 external flash (linker FLASH = 0x70000000) */\n"], [], [], []
    for i, c in enumerate(payload["cells"]["val"]):
        T = np.asarray(c["tensor"], np.float32); k = min(100, int(c["observed_cycles"]), int(np.ceil(c["eol"])) - 1)
        h = np.concatenate([sE.run(None, {"curve": T[t:t + 1]})[0] for t in range(k)])
        g = np.concatenate([sF.run(None, {"h": h[t:t + 1], "h1": h[:1]})[0] for t in range(k)])
        S = summaries(g.astype(np.float64)).astype(np.float32)
        ref = np.array([mu + s * sH.run(None, {"summary": S[n:n + 1]})[0].item() for n in range(k)])
        parts.append(arr(f"zn_c{i}_curves", T[:k])); parts.append(arr(f"zn_c{i}_ref", ref))
        cells.append(f"{{{k},{float(c['eol'])!r}f,zn_c{i}_curves,zn_c{i}_ref}}")
        mape_ref.extend(np.abs(ref - c["eol"]) / c["eol"])
    parts.append("const zn_cell_t zn_cells[] = {" + ",".join(cells) + "};\n")
    parts.append(f"const int zn_ncells = {len(cells)};\n")
    (FW / "zn_data.c").write_text("".join(parts))
    print(f"{eid} split {split}: {len(cells)} val cells, {len(mape_ref)} prefixes, host reference val MAPE {np.mean(mape_ref):.6f}")
